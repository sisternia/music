import { useEffect, useMemo, useRef, useState } from 'react';
import { midiNoteName, songAsset, type PianoSong } from '../hooks/transcription';
import { usePianoPlayback, visibleNoteRange, type PlaybackAudio } from '../hooks/usePianoPlayback';
import { useScoreEditor } from '../hooks/useScoreEditor';
import ScorePalette from './ScorePalette';
import { PIANO_EDITION_ENABLED } from '../hooks/features';

type Props = { song: PianoSong; audio: PlaybackAudio; onActiveNotes: (notes: Set<string>) => void; onClose: () => void; onSongChange: (song: PianoSong) => void; onNewTranscription?: () => void; startInEdition?: boolean; onEditionChange?: (edition: boolean) => void };

function clock(value: number) {
  return `${Math.floor(value / 60)}:${String(Math.floor(value % 60)).padStart(2, '0')}`;
}

// Score SVGs are generated by our server; strip executable content before inline highlighting.
export function safeScoreSvg(value: string) {
  const document = new DOMParser().parseFromString(value, 'image/svg+xml');
  const root = document.documentElement;
  if (root.localName !== 'svg' || document.querySelector('parsererror')) throw new Error('Trang phổ nhạc không hợp lệ.');
  document.querySelectorAll('script, foreignObject, iframe, object, embed, image, a').forEach(node => node.remove());
  document.querySelectorAll('*').forEach(node => {
    for (const attr of [...node.attributes]) {
      if (/^on/i.test(attr.name) || (/href$/i.test(attr.name) && !attr.value.startsWith('#'))) node.removeAttribute(attr.name);
    }
  });
  return new XMLSerializer().serializeToString(root);
}

export default function PianoSongPlayer({ song, audio, onActiveNotes, onClose, onSongChange, onNewTranscription, startInEdition = false, onEditionChange }: Props) {
  const playback = usePianoPlayback(song, audio);
  const { playing, readTime, speed, error, play, pause, seek, changeSpeed } = playback;
  const [mode, setMode] = useState<'reading' | 'edition'>(PIANO_EDITION_ENABLED && startInEdition ? 'edition' : 'reading');
  const [zoom, setZoom] = useState(100);
  const [downloadsOpen, setDownloadsOpen] = useState(false);
  const editor = useScoreEditor(song, mode === 'edition', onSongChange, pause);
  const [selectionBox, setSelectionBox] = useState<{ x: number; y: number; width: number; height: number } | null>(null);
  const drag = useRef<{ x: number; y: number; add: boolean } | null>(null);
  const [time, setTime] = useState(0);
  const [page, setPage] = useState(1);
  const [follow, setFollow] = useState(true);
  const [scoreData, setScoreData] = useState<{ url: string; svg: string; error: string } | null>(null);
  const canvas = useRef<HTMLCanvasElement>(null);
  const score = useRef<HTMLDivElement>(null);
  const callback = useRef(onActiveNotes);
  useEffect(() => { callback.current = onActiveNotes; }, [onActiveNotes]);
  const longest = useMemo(() => song.notes.reduce((max, note) => Math.max(max, note.end - note.start), 0), [song.notes]);
  const cache = useRef(new Map<string, string>());
  const pageUrl = songAsset(song, song.pages[page - 1] || '');
  const svg = scoreData?.url === pageUrl ? scoreData.svg : '';
  const scoreMarkup = useMemo(() => ({ __html: svg }), [svg]);
  const scoreError = scoreData?.url === pageUrl ? scoreData.error : '';

  useEffect(() => {
    score.current?.querySelectorAll('.score-selected').forEach(node => node.classList.remove('score-selected'));
    if (mode === 'edition') for (const id of editor.selected) score.current?.querySelector(`[id="${CSS.escape(id)}"]`)?.classList.add('score-selected');
  }, [editor.selected, svg, mode]);

  useEffect(() => {
    if (mode !== 'edition') return;
    score.current?.querySelectorAll<SVGGraphicsElement>('.note, .rest, .mRest').forEach(element => {
      if (element.querySelector('[data-editor-hit]')) return;
      const bounds = element.getBBox();
      const hit = document.createElementNS('http://www.w3.org/2000/svg', 'rect');
      hit.setAttribute('data-editor-hit', 'true');
      hit.setAttribute('x', String(bounds.x - 25)); hit.setAttribute('y', String(bounds.y - 25));
      hit.setAttribute('width', String(Math.max(150, bounds.width + 50))); hit.setAttribute('height', String(Math.max(150, bounds.height + 50)));
      hit.setAttribute('fill', 'transparent'); hit.setAttribute('stroke', 'none'); hit.setAttribute('pointer-events', 'all');
      element.insertBefore(hit, element.firstChild);
    });
  }, [svg, mode]);

  useEffect(() => {
    if (mode !== 'edition') return;
    const keydown = (event: KeyboardEvent) => {
      if (event.target instanceof HTMLElement && event.target.closest('input,textarea,select,[contenteditable]')) return;
      if ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === 'z') {
        event.preventDefault(); if (event.shiftKey) editor.redo(); else editor.undo();
      } else if (editor.selected.length && ['Delete', 'Backspace'].includes(event.key)) {
        event.preventDefault(); void editor.apply('delete');
      } else if (editor.selected.length && ['ArrowUp', 'ArrowDown'].includes(event.key)) {
        event.preventDefault(); void editor.apply('transpose', (event.key === 'ArrowUp' ? 1 : -1) * (event.shiftKey ? 12 : 1));
      }
    };
    window.addEventListener('keydown', keydown);
    return () => window.removeEventListener('keydown', keydown);
  }, [mode, editor]);

  useEffect(() => {
    const name = song.pages[page - 1];
    if (!name) return;
    const controller = new AbortController();
    const url = songAsset(song, name);
    const load = async () => {
      try {
        let safe = cache.current.get(url);
        if (!safe) {
          const response = await fetch(url, { signal: controller.signal });
          if (!response.ok) throw new Error('Không tải được trang phổ nhạc.');
          safe = safeScoreSvg(await response.text());
          cache.current.set(url, safe);
        }
        // Let the current page commit before publishing cached content too.
        await Promise.resolve();
        if (!controller.signal.aborted) setScoreData({ url, svg: safe, error: '' });
      } catch (reason) {
        if (!controller.signal.aborted) setScoreData({ url, svg: '', error: reason instanceof Error ? reason.message : 'Không tải được phổ nhạc.' });
      }
    };
    void load();
    return () => controller.abort();
  }, [song, page]);

  useEffect(() => {
    const target = canvas.current;
    if (!target) return;
    const context = target.getContext('2d');
    if (!context) return;
    let frame = 0;
    let width = 1;
    let height = 1;
    let dpr = 1;
    const positions = new Map<number, { x: number; width: number }>();
    const resize = () => {
      const bounds = target.getBoundingClientRect();
      width = bounds.width; height = bounds.height;
      dpr = Math.min(window.devicePixelRatio || 1, 2);
      target.width = Math.max(1, Math.round(width * dpr));
      target.height = Math.max(1, Math.round(height * dpr));
      positions.clear();
      const keyboard = target.closest('.piano-page')?.querySelector('.keyboard');
      for (let pitch = 21; pitch <= 108; pitch++) {
        const note = midiNoteName(pitch);
        const row = note.includes('#') ? '.top-keys' : '.bottom-keys';
        const key = keyboard?.querySelector(`${row} button[data-note="${note}"]`);
        if (key) {
          const rect = key.getBoundingClientRect();
          positions.set(pitch, { x: rect.left - bounds.left, width: rect.width });
        }
      }
    };
    const observer = new ResizeObserver(resize);
    observer.observe(target);
    const keyboard = target.closest('.piano-page')?.querySelector('.keyboard');
    if (keyboard) observer.observe(keyboard);
    resize();
    let lastPublish = -1;
    let signature = '';
    let timelineIndex = 0;
    let lastTime = -1;
    let currentPage = 1;
    const activeIds = new Set<string>();
    const draw = () => {
      const now = readTime();
      context.setTransform(dpr, 0, 0, dpr, 0, 0);
      context.clearRect(0, 0, width, height);
      context.fillStyle = '#19211f'; context.fillRect(0, 0, width, height);
      context.strokeStyle = '#34433e'; context.lineWidth = 0.5;
      for (const [pitch, position] of positions) {
        if (!midiNoteName(pitch).includes('#')) {
          context.beginPath(); context.moveTo(position.x, 0); context.lineTo(position.x, height); context.stroke();
        }
      }
      const active = new Set<string>();
      const [start, end] = visibleNoteRange(song, now, 4, longest);
      for (let index = start; index < end; index++) {
        const note = song.notes[index];
        if (note.end <= now) continue;
        const key = positions.get(note.pitch);
        if (!key) continue;
        const y = height - (note.start - now) / 4 * height;
        const top = height - (note.end - now) / 4 * height;
        const bottom = Math.min(height, y);
        const visibleTop = Math.max(0, top);
        if (bottom <= 0 || visibleTop >= height || bottom <= visibleTop) continue;
        // Use the same per-key hue as the Piano tab's Cinema glow.
        const hue = (((note.pitch - 24) * 7.2) % 360 + 360) % 360;
        const color = `hsl(${hue} 85% 68%)`;
        context.fillStyle = color;
        if (note.start <= now) {
          active.add(midiNoteName(note.pitch));
        }
        context.shadowColor = color;
        context.shadowBlur = note.start <= now ? 12 : 5;
        context.beginPath();
        context.roundRect(key.x + 1, visibleTop, Math.max(1, key.width - 2), Math.max(2, bottom - visibleTop), 4);
        context.fill();
      }
      context.shadowBlur = 0;
      context.fillStyle = '#88b2aa'; context.fillRect(0, height - 2, width, 2);
      // Publish only when note membership changes, rather than rerendering 88 keys every frame.
      const nextSignature = [...active].sort().join(',');
      if (nextSignature !== signature) {
        signature = nextSignature;
        callback.current(active);
      }
      if (now < lastTime) { timelineIndex = 0; activeIds.clear(); currentPage = 1; }
      while (timelineIndex < song.timeline.length && song.timeline[timelineIndex].time <= now) {
        const event = song.timeline[timelineIndex++];
        event.off.forEach(id => activeIds.delete(id));
        event.on.forEach(id => activeIds.add(id));
        if (event.page) currentPage = event.page;
      }
      lastTime = now;
      if (performance.now() - lastPublish > 100) {
        lastPublish = performance.now();
        setTime(now);
        if (follow) setPage(Math.min(song.pages.length, Math.max(1, currentPage)));
        const root = score.current;
        root?.querySelectorAll('.playing-note').forEach(node => node.classList.remove('playing-note'));
        for (const id of activeIds) root?.querySelector(`[id="${CSS.escape(id)}"]`)?.classList.add('playing-note');
        if (follow && activeIds.size && root) {
          const first = root.querySelector(`[id="${CSS.escape([...activeIds][0])}"]`);
          if (first) {
            const bounds = first.getBoundingClientRect();
            const viewport = root.getBoundingClientRect();
            if (bounds.top < viewport.top + 15 || bounds.bottom > viewport.bottom - 15) {
              root.scrollTop += bounds.top - viewport.top - viewport.height / 3;
            }
            if (bounds.left < viewport.left + 15 || bounds.right > viewport.right - 15) {
              root.scrollLeft += bounds.left - viewport.left - viewport.width / 3;
            }
          }
        }
      }
      frame = requestAnimationFrame(draw);
    };
    frame = requestAnimationFrame(draw);
    return () => { cancelAnimationFrame(frame); observer.disconnect(); callback.current(new Set()); };
  }, [song, readTime, longest, follow, mode]);

  return (
    <div className={`piano-song-player ${mode === 'edition' ? 'score-edition' : 'score-reading'}`}>
      <div className="piano-song-heading">
        <div className="score-title-block"><h2>{song.title}</h2><small>Piano · ♩ {Math.round(song.bpm)} · {song.meter}</small></div>
        <div className="score-header-actions">{mode === 'edition' && <><span className="score-save-status">{editor.busy ? '◌ Đang lưu…' : '✓ Đã lưu'}</span><button disabled={!editor.canUndo || editor.busy} onClick={editor.undo} title="Undo · Ctrl+Z" aria-label="Undo">↶</button><button disabled={!editor.canRedo || editor.busy} onClick={editor.redo} title="Redo · Ctrl+Shift+Z" aria-label="Redo">↷</button></>}<div className="score-download-wrap"><button className="score-download" onClick={() => setDownloadsOpen(value => !value)}>↓ Download</button>{downloadsOpen && <div className="score-download-menu">{Object.entries(song.downloads).map(([kind, name]) => <a key={kind} href={songAsset(song, name)} target="_blank" rel="noreferrer" onClick={() => setDownloadsOpen(false)}>{kind.toUpperCase()} ↓</a>)}</div>}</div><button onClick={() => { pause(); onNewTranscription?.(); }} title="New transcription">↻ <span>New transcription</span></button></div>
        {PIANO_EDITION_ENABLED && <div className="score-mode-switch" role="tablist" aria-label="Chế độ bản nhạc"><button role="tab" aria-selected={mode === 'reading'} onClick={() => { setMode('reading'); onEditionChange?.(false); }}>Reading</button><button role="tab" aria-selected={mode === 'edition'} onClick={() => { pause(); setFollow(false); setMode('edition'); onEditionChange?.(true); }}>Edition</button></div>}
      </div>
      <div className="score-work-area">
      {mode === 'edition' && <ScorePalette editor={editor} />}
      <div className="score-sheet-column">
      <div className="piano-score-navigation">
        <button onClick={() => { setFollow(false); setPage(value => Math.max(1, value - 1)); }} disabled={page <= 1}>‹</button>
        <span>Trang {page} / {song.pages.length}</span>
        <button onClick={() => { setFollow(false); setPage(value => Math.min(song.pages.length, value + 1)); }} disabled={page >= song.pages.length}>›</button>
        <label><input type="checkbox" checked={follow} onChange={event => setFollow(event.target.checked)} /> Theo bản nhạc</label>
        <div className="score-zoom"><button onClick={() => setZoom(value => Math.max(50, value - 10))} aria-label="Thu nhỏ phổ">−</button><span>{zoom}%</span><button onClick={() => setZoom(value => Math.min(180, value + 10))} aria-label="Phóng to phổ">＋</button></div>
      </div>
      <div className="piano-score-scroll" ref={score}
        onClick={event => {
          if (mode !== 'edition' || editor.busy) return;
          const element = event.target instanceof Element ? event.target.closest('.note, .rest, .mRest') : null;
          const id = element?.id;
          if (!id || !editor.notes.some(note => note.id === id)) return;
          editor.setSelected(current => event.shiftKey || event.ctrlKey || event.metaKey ? current.includes(id) ? current.filter(value => value !== id) : [...current, id] : [id]);
        }}
        onPointerDown={event => {
          if (mode !== 'edition' || editor.busy || event.pointerType === 'touch' || event.button !== 0) return;
          if (event.target instanceof Element && event.target.closest('.note, .rest, .mRest')) return;
          drag.current = { x: event.clientX, y: event.clientY, add: event.shiftKey };
          event.currentTarget.setPointerCapture(event.pointerId);
        }}
        onPointerMove={event => {
          if (!drag.current) return;
          const bounds = event.currentTarget.getBoundingClientRect();
          setSelectionBox({ x: Math.min(event.clientX, drag.current.x) - bounds.left + event.currentTarget.scrollLeft, y: Math.min(event.clientY, drag.current.y) - bounds.top + event.currentTarget.scrollTop, width: Math.abs(event.clientX - drag.current.x), height: Math.abs(event.clientY - drag.current.y) });
        }}
        onPointerUp={event => {
          if (!drag.current) return;
          const start = drag.current;
          const left = Math.min(start.x, event.clientX), right = Math.max(start.x, event.clientX);
          const top = Math.min(start.y, event.clientY), bottom = Math.max(start.y, event.clientY);
          const ids = [...event.currentTarget.querySelectorAll('.note, .rest, .mRest')].filter(element => {
            const bounds = element.getBoundingClientRect();
            return bounds.right >= left && bounds.left <= right && bounds.bottom >= top && bounds.top <= bottom;
          }).map(element => element.id).filter(id => editor.notes.some(note => note.id === id));
          editor.setSelected(current => start.add ? [...new Set([...current, ...ids])] : ids);
          drag.current = null; setSelectionBox(null);
        }} onPointerCancel={() => { drag.current = null; setSelectionBox(null); }}>
        {scoreError ? <p role="alert">{scoreError}</p> : svg ? <div className="piano-score-svg" style={{ width: `${zoom}%`, maxWidth: 'none' }} dangerouslySetInnerHTML={scoreMarkup} /> : <p>Đang tải phổ nhạc…</p>}
        {selectionBox && <div className="score-selection-box" style={{ left: selectionBox.x, top: selectionBox.y, width: selectionBox.width, height: selectionBox.height }} />}
      </div>
      {mode === 'edition' && <div className="score-edition-status"><span>{editor.selected.length ? `${editor.selected.length} nốt / dấu lặng được chọn` : 'Chọn nốt trên phổ · Shift + nhấp hoặc kéo để chọn nhiều'}</span><button onClick={() => editor.setSelected([])} disabled={!editor.selected.length}>Bỏ chọn</button></div>}
      </div></div>
      {editor.error && mode === 'edition' && <div className="score-editor-error" role="alert">{editor.error}</div>}
      {mode === 'reading' && <>
      <div className="piano-song-transport">
        <button className="piano-song-play" disabled={!audio.isReady} title={audio.isReady ? 'Phát piano' : 'Đang tải âm thanh piano…'} onClick={() => { if (playing) pause(); else void play(); }} aria-label={playing ? 'Tạm dừng' : 'Phát piano'}>{playing ? 'Ⅱ' : '▶'}</button>
        {!audio.isReady && <span className="piano-audio-status" role="status">Đang tải tiếng đàn…</span>}
        <button onClick={() => seek(0)} aria-label="Về đầu bài">↤</button>
        <span className="piano-song-clock">{clock(time)} / {clock(song.duration)}</span>
        <input aria-label="Vị trí bản nhạc" type="range" min={0} max={song.duration} step={0.05} value={time} onChange={event => seek(Number(event.target.value))} />
        <select aria-label="Tốc độ phát" value={speed} onChange={event => changeSpeed(Number(event.target.value))}>{[0.5, 0.75, 1, 1.25, 1.5].map(value => <option key={value} value={value}>{value}×</option>)}</select>
      </div>
      {error && <div className="piano-player-error" role="alert">{error}</div>}
      <canvas className="piano-falling-notes" ref={canvas} aria-label="Nốt piano rơi đồng bộ với bản nhạc" />
      </>}
    </div>
  );
}
